package org.jevis.commons.ws.json;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;

import java.util.ArrayList;
import java.util.List;

/**
 * A role of a user with the group rights it grants (OpenJEVis #1211).
 */
@JsonInclude(JsonInclude.Include.NON_NULL)
@JsonIgnoreProperties(ignoreUnknown = true)
public class JsonRoleRights {

    private long roleId;
    private String roleName;
    private List<JsonGroupRights> groups = new ArrayList<>();

    public long getRoleId() {
        return roleId;
    }

    public void setRoleId(long roleId) {
        this.roleId = roleId;
    }

    public String getRoleName() {
        return roleName;
    }

    public void setRoleName(String roleName) {
        this.roleName = roleName;
    }

    public List<JsonGroupRights> getGroups() {
        return groups;
    }

    public void setGroups(List<JsonGroupRights> groups) {
        this.groups = groups;
    }
}
